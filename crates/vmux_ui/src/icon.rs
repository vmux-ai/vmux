    #[component]
    pub fn PageIconView(
        icon: PageIcon,
        url: String,
        img_class: String,
        icon_class: String,
    ) -> Element {
        if url.starts_with("file:") {
            let is_dir = url.ends_with('/');
            return rsx! { TypeIcon { path: url, is_dir, class: icon_class } };
        }
        if let PageIcon::Builtin(builtin) = &icon {
            return rsx! { BuiltinIconView { icon: *builtin, class: icon_class } };
        }
        let favicon_url = icon.favicon_url().to_string();
        rsx! {
            Favicon {
                favicon_url,
                url,
                class: img_class,
                globe_class: icon_class,
            }
        }
    }
