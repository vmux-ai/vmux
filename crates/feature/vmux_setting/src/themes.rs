    pub fn resolve(name: &str, custom_themes: &[Self]) -> Self {
        if let Some(theme) = custom_themes.iter().find(|theme| theme.name == name) {
            return theme.clone();
        }
        if let Some(theme) = Self::builtins()
            .into_iter()
            .find(|theme| theme.name == name)
        {
            return theme;
        }
        eprintln!(
            "Unknown terminal theme '{}', falling back to catppuccin-mocha",
            name
        );
        Self::builtins().into_iter().next().unwrap()
    }
